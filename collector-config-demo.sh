#!/usr/bin/env bash
# Generate a collector extras config that forwards the demo telemetry to your
# own OTLP/HTTP endpoints and stamps custom resource attributes on the telemetry
# of one service.
#
# Usage:
#   ./collector-config-demo.sh --traces-url <url> --logs-url <url> \
#       [--resource-attribute key=value]... [--service <name>] [--out <path>] \
#       [-- <compose args>...]
#
# Options:
#   --traces-url <url>             OTLP/HTTP URL for traces, used verbatim, so a
#                                  token in the path or query is preserved.
#   --logs-url <url>               OTLP/HTTP URL for logs, used verbatim.
#   --resource-attribute key=value Resource attribute to set. Repeat the flag for
#                                  as many attributes as you need.
#   --service <name>               Service whose telemetry gets the attributes.
#                                  Defaults to frontend-web. Use "all" for every
#                                  service.
#   --out <path>                   Where to write the generated config.
#                                  Defaults to .collector-config-demo/otelcol-config-generated.yml
#   -- <compose args>              Run docker compose with these arguments instead
#                                  of recreating the collector, e.g. -- up -d.
#
# The generated file is pointed at by OTEL_COLLECTOR_CONFIG_EXTRAS in
# .env.override. It is written under a gitignored directory and must never be
# committed: it holds your endpoints, including any token embedded in them.

set -euo pipefail

usage() {
  sed -n '2,28p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

TRACES_URL=""
LOGS_URL=""
SERVICE="frontend-web"
OUT_FILE=".collector-config-demo/otelcol-config-generated.yml"
ATTRIBUTES=()
COMPOSE_ARGS=()

while [ "$#" -gt 0 ]; do
  case "$1" in
    --traces-url) TRACES_URL="${2:-}"; shift 2 ;;
    --logs-url) LOGS_URL="${2:-}"; shift 2 ;;
    --service) SERVICE="${2:-}"; shift 2 ;;
    --out) OUT_FILE="${2:-}"; shift 2 ;;
    --resource-attribute)
      case "${2:-}" in
        *=*) ATTRIBUTES+=("$2") ;;
        *) echo "error: --resource-attribute expects key=value, got '${2:-}'" >&2; exit 64 ;;
      esac
      shift 2 ;;
    -h|--help) usage; exit 0 ;;
    --) shift; COMPOSE_ARGS=("$@"); break ;;
    *) echo "error: unknown argument '$1'" >&2; usage >&2; exit 64 ;;
  esac
done

for pair in "--traces-url:$TRACES_URL" "--logs-url:$LOGS_URL"; do
  flag="${pair%%:*}"
  url="${pair#*:}"
  case "$url" in
    http://*|https://*) ;;
    "") echo "error: $flag is required" >&2; exit 64 ;;
    *) echo "error: $flag must be an absolute http(s) URL, got '$url'" >&2; exit 64 ;;
  esac
done

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$REPO_ROOT"

# Read the processor lists from the base config and the exporter lists from the
# observability layer, so the generated pipelines keep whatever those files
# declare instead of a stale copy of them.
pipeline_members() {
  python3 - "$1" "$2" "$3" <<'PY'
import sys, yaml
path, pipeline, key = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path) as fh:
    cfg = yaml.safe_load(fh) or {}
members = (cfg.get("service", {}).get("pipelines", {}).get(pipeline, {}) or {}).get(key) or []
print(", ".join(members))
PY
}

if ! python3 -c 'import yaml' 2>/dev/null; then
  echo "error: python3 with PyYAML is required to read the collector config" >&2
  exit 69
fi

BASE_CONFIG="src/otel-collector/otelcol-config.yml"
OBSERVABILITY_CONFIG="src/otel-collector/otelcol-config-observability.yml"

TRACE_PROCESSORS="$(pipeline_members "$BASE_CONFIG" traces processors)"
LOG_PROCESSORS="$(pipeline_members "$BASE_CONFIG" logs processors)"
TRACE_EXPORTERS="$(pipeline_members "$OBSERVABILITY_CONFIG" traces exporters)"
LOG_EXPORTERS="$(pipeline_members "$OBSERVABILITY_CONFIG" logs exporters)"

ottl_escape() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }

ATTRIBUTE_STATEMENTS=""
if [ "${#ATTRIBUTES[@]}" -gt 0 ]; then
  if [ "$SERVICE" = "all" ]; then
    WHERE=""
  else
    WHERE=" where attributes[\"service.name\"] == \"$(ottl_escape "$SERVICE")\""
  fi
  for pair in "${ATTRIBUTES[@]}"; do
    key="$(ottl_escape "${pair%%=*}")"
    value="$(ottl_escape "${pair#*=}")"
    ATTRIBUTE_STATEMENTS+="          - set(attributes[\"${key}\"], \"${value}\")${WHERE}"$'\n'
  done
fi

mkdir -p "$(dirname "$OUT_FILE")"

{
  echo "# Generated by collector-config-demo.sh. Do not commit, do not edit by hand."
  echo
  echo "exporters:"
  echo "  otlp_http/demo_traces:"
  echo "    traces_endpoint: \"${TRACES_URL}\""
  echo "  otlp_http/demo_logs:"
  echo "    logs_endpoint: \"${LOGS_URL}\""

  if [ -n "$ATTRIBUTE_STATEMENTS" ]; then
    echo
    echo "processors:"
    echo "  transform/demo_resource_attributes:"
    echo "    error_mode: ignore"
    echo "    trace_statements:"
    echo "      - context: resource"
    echo "        statements:"
    printf '%s' "$ATTRIBUTE_STATEMENTS"
    echo "    log_statements:"
    echo "      - context: resource"
    echo "        statements:"
    printf '%s' "$ATTRIBUTE_STATEMENTS"
    TRACE_PROCESSORS="${TRACE_PROCESSORS}, transform/demo_resource_attributes"
    LOG_PROCESSORS="${LOG_PROCESSORS}, transform/demo_resource_attributes"
  fi

  echo
  echo "service:"
  echo "  pipelines:"
  echo "    traces:"
  echo "      processors: [${TRACE_PROCESSORS}]"
  echo "      exporters: [${TRACE_EXPORTERS}, otlp_http/demo_traces]"
  echo "    logs:"
  echo "      processors: [${LOG_PROCESSORS}]"
  echo "      exporters: [${LOG_EXPORTERS}, otlp_http/demo_logs]"
} > "$OUT_FILE"

touch .env.override
if grep -q '^OTEL_COLLECTOR_CONFIG_EXTRAS=' .env.override; then
  sed -i.bak "s|^OTEL_COLLECTOR_CONFIG_EXTRAS=.*|OTEL_COLLECTOR_CONFIG_EXTRAS=./${OUT_FILE}|" .env.override
  rm -f .env.override.bak
else
  echo "OTEL_COLLECTOR_CONFIG_EXTRAS=./${OUT_FILE}" >> .env.override
fi

echo "wrote ${OUT_FILE} (gitignored, never commit it)"
echo "set OTEL_COLLECTOR_CONFIG_EXTRAS in .env.override, which is a local file: do not push it"
echo "  traces endpoint    : ${TRACES_URL}"
echo "  logs endpoint      : ${LOGS_URL}"
if [ "${#ATTRIBUTES[@]}" -gt 0 ]; then
  echo "  resource attributes: ${ATTRIBUTES[*]} (service: ${SERVICE})"
else
  echo "  resource attributes: none"
fi

COMPOSE=(docker compose --env-file .env --env-file .env.override
         -f compose.yaml -f compose.full.yaml -f compose.observability.yaml -f compose.extras.yaml)

if [ "${#COMPOSE_ARGS[@]}" -gt 0 ]; then
  exec "${COMPOSE[@]}" "${COMPOSE_ARGS[@]}"
fi

"${COMPOSE[@]}" up -d --no-deps --force-recreate otel-collector
